import { execFileSync } from "node:child_process"
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { afterEach, beforeEach, expect, it } from "vitest"
import { projectDependencies } from "../src/project.js"
import { inventoryWorkspace } from "../src/workspace/inventory.js"
import { parseLockfile } from "../src/lockfiles.js"

let bunAvailable = false
try { execFileSync("bun", ["--version"], { stdio: "ignore", timeout: 5000 }); bunAvailable = true } catch { /* Text locks do not require Bun. */ }
let root: string
const manifest = () => ({
  name: "catalog-fixture", private: true,
  workspaces: {
    packages: ["packages/*"], catalog: { "is-odd": "3.0.1" },
    catalogs: { legacy: { renamed: "npm:is-number@6.0.0" }, modern: { number7: "npm:is-number@7.0.0" } },
  },
  dependencies: { "is-odd": "catalog:", renamed: "catalog:legacy", number7: "catalog:modern" },
})
// Generated by Bun 1.3.9 with saveTextLockfile=false, --lockfile-only and --ignore-scripts.
const bytes = readFileSync(new URL("./fixtures/lockfiles/bun-catalog.lockb", import.meta.url))
beforeEach(() => {
  root = realpathSync(mkdtempSync(join(tmpdir(), "typelatch-binary-catalog-")))
  execFileSync("git", ["init", "-q", root])
  mkdirSync(join(root, "packages/app"), { recursive: true })
  writeFileSync(join(root, "package.json"), JSON.stringify(manifest()))
  writeFileSync(join(root, "packages/app/package.json"), JSON.stringify({ name: "app", version: "1.0.0", dependencies: { renamed: "catalog:legacy" } }))
  writeFileSync(join(root, "bun.lockb"), bytes)
})
afterEach(() => rmSync(root, { recursive: true, force: true }))

it.skipIf(!bunAvailable)("resolves catalog aliases from a real binary Bun lock without losing package identity", async () => {
  expect(await projectDependencies(root)).toEqual([
    { name: "is-odd", version: "3.0.1" },
    { name: "is-number", version: "7.0.0", alias: "number7" },
    { name: "is-number", version: "6.0.0", alias: "renamed" },
  ])
  expect(await projectDependencies(join(root, "packages/app"))).toEqual([{ name: "is-number", version: "6.0.0", alias: "renamed" }])
  const inventory = await inventoryWorkspace(root, true, new AbortController().signal)
  expect(inventory.issues).toEqual([])
  expect(inventory.dependencies.map(item => `${item.package}@${item.version}`).sort()).toEqual(["is-number@6.0.0", "is-number@7.0.0", "is-odd@3.0.1"])
  expect(inventory.dependencies.every(item => item.integrity?.startsWith("sha512-"))).toBe(true)
  expect(readFileSync(join(root, "bun.lockb"))).toEqual(bytes)
})

it.skipIf(!bunAvailable)("does not infer a different catalog alias from another locked package", async () => {
  const changed = manifest()
  changed.workspaces.catalogs.legacy.renamed = "npm:is-odd@3.0.1"
  writeFileSync(join(root, "package.json"), JSON.stringify(changed))
  await expect(projectDependencies(join(root, "packages/app"))).rejects.toThrow("No exact locked registry identity for renamed")
  expect(readFileSync(join(root, "bun.lockb"))).toEqual(bytes)
})

it.skipIf(!bunAvailable)("does not reuse an old binary catalog resolution after its exact requested version changes", () => {
  const catalogs = manifest().workspaces
  catalogs.catalogs.legacy.renamed = "npm:is-number@7.0.0"
  const lock = parseLockfile(join(root, "bun.lockb"), bytes.toString("latin1"), { bunCatalogs: JSON.stringify(catalogs) })
  expect(lock.direct(root, "renamed", "catalog:legacy")).toBeUndefined()
})

it.skipIf(!bunAvailable)("reads top-level catalog fields alongside an object workspace declaration", async () => {
  const original = manifest()
  const changed = { ...original, workspaces: { packages: original.workspaces.packages }, catalog: original.workspaces.catalog, catalogs: original.workspaces.catalogs }
  writeFileSync(join(root, "package.json"), JSON.stringify(changed))
  expect(await projectDependencies(root)).toEqual([
    { name: "is-odd", version: "3.0.1" },
    { name: "is-number", version: "7.0.0", alias: "number7" },
    { name: "is-number", version: "6.0.0", alias: "renamed" },
  ])
})
