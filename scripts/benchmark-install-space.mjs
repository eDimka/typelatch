import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { lstatSync, mkdirSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs'
import { arch, platform } from 'node:os'
import { join, relative, resolve } from 'node:path'
import { gzipSync } from 'node:zlib'

const [codegraphRoot, graphifyPython] = process.argv.slice(2)
if (!codegraphRoot || !graphifyPython) throw new Error('Usage: node scripts/benchmark-install-space.mjs <isolated-codegraph-install> <isolated-graphify-python>')
const root = resolve('artifacts/competitive/install-space', new Date().toISOString().replaceAll(':', '-'))
mkdirSync(root, { recursive: true })
const run = (cmd, args, options = {}) => execFileSync(cmd, args, { encoding: 'utf8', timeout: 180_000, ...options })
const packed = JSON.parse(run('npm', ['pack', '--json', '--ignore-scripts', '--pack-destination', root]))[0]
const install = join(root, 'typelatch-install')
mkdirSync(install)
writeFileSync(join(install, 'package.json'), JSON.stringify({ private: true }))
run('npm', ['install', '--omit=dev', '--no-audit', '--no-fund', join(root, packed.filename)], { cwd: install })
const python = JSON.parse(run(graphifyPython, ['-c', 'import sys, sysconfig, json; from importlib.metadata import version; print(json.dumps({"version":version("graphifyy"),"site":sysconfig.get_path("purelib"),"runtime":sys.base_prefix,"python":sys.version}))']))
const manifests = {}
function measure(label, directory) {
  const files = []
  const walk = path => {
    const stat = lstatSync(path)
    if (stat.isSymbolicLink()) return
    if (stat.isDirectory()) { for (const name of readdirSync(path).sort()) walk(join(path, name)); return }
    if (stat.isFile()) files.push({ path: relative(directory, path) || '<executable>', bytes: stat.size, allocatedBytes: stat.blocks * 512 })
  }
  walk(directory)
  manifests[label] = files
  return { files: files.length, bytes: files.reduce((n, file) => n + file.bytes, 0), allocatedBytes: files.reduce((n, file) => n + file.allocatedBytes, 0) }
}
const graphRoot = resolve(codegraphRoot, 'node_modules')
const graphPackage = JSON.parse(readFileSync(join(graphRoot, '@colbymchenry/codegraph/package.json'), 'utf8'))
const runtimePackage = join(graphRoot, `@colbymchenry/codegraph-${platform()}-${arch()}`)
const report = {
  generatedAt: new Date().toISOString(), kind: 'Installed tool and dependency files, runtimes reported separately',
  environment: { platform: platform(), arch: arch(), node: process.version, python: python.python },
  methodology: 'Typelatch is packed from this checkout and installed with production dependencies into an empty project. CodeGraph is its isolated npm installation. Graphify is its isolated default Python environment. Sum regular file sizes, excluding symlinks. Allocated bytes sum stat blocks and do not measure physically reclaimable APFS space. No graph indexes, checkout clones, npm or uv download caches are included.',
  limitations: 'Different language surfaces and runtimes. CodeGraph bundles Node, so its tool total includes that binary; its value is itemized separately. Typelatch requires an existing Node interpreter. Graphify requires a Python distribution, reported separately including its standard library. Python bytecode generated by actual execution is included. No model weights were installed for this Graphify code extraction run. These are not total machine provisioning or RAM figures.',
  tools: {
    typelatch: { version: JSON.parse(readFileSync('package.json', 'utf8')).version, source: 'working checkout', productionInstall: measure('typelatch', join(install, 'node_modules')), packageTarballBytes: packed.size, packageUnpackedBytes: packed.unpackedSize },
    codegraph: { version: graphPackage.version, source: 'npm @colbymchenry/codegraph', productionInstallIncludingNode: measure('codegraph', graphRoot), bundledNode: measure('codegraph-node', join(runtimePackage, 'node')) },
    graphify: { version: python.version, source: 'official pinned source installed with default dependencies', defaultInstall: measure('graphify', python.site) }
  },
  runtimes: { typelatchNodeExecutable: measure('node-runtime', realpathSync(process.execPath)), graphifyPythonDistribution: measure('python-runtime', python.runtime) },
  packageIntegrity: packed.integrity
}
const raw = gzipSync(JSON.stringify(manifests))
writeFileSync(join(root, 'files.json.gz'), raw)
const dependencyLock = readFileSync(join(install, 'package-lock.json'))
writeFileSync(join(root, 'typelatch-package-lock.json'), dependencyLock)
report.installedDependencyLock = { path: relative(resolve('.'), join(root, 'typelatch-package-lock.json')), sha256: createHash('sha256').update(dependencyLock).digest('hex') }
report.raw = { path: relative(resolve('.'), join(root, 'files.json.gz')), sha256: createHash('sha256').update(raw).digest('hex') }
writeFileSync(join(root, 'report.json'), JSON.stringify(report, null, 2) + '\n')
mkdirSync('docs/benchmarks', { recursive: true })
writeFileSync('docs/benchmarks/install-space.json', JSON.stringify(report, null, 2) + '\n')
console.log(JSON.stringify(report, null, 2))
